"""Traceability of every number SYNAPSE shows: shared/sources.json, shared/hrp.json and the
`provenance` of each scenario. Renders docs/sources.md.

uv run python scripts/provenance.py   # rewrite docs/sources.md
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SHARED = ROOT / "shared"
DOC = ROOT / "docs" / "sources.md"
REQUIRED_CLAIMS = ("expect.status", "expect.escalation", "expect.hrpRisk", "expect.affectedSystems")


def load(path: Path):
    return json.loads(path.read_text(encoding="utf-8"))


def sources():
    return load(SHARED / "sources.json")["sources"]


def scenarios():
    return [load(p) for p in sorted((SHARED / "scenarios").glob("*.json"))]


def leaves(value, prefix):
    if isinstance(value, dict):
        for key, child in value.items():
            yield from leaves(child, f"{prefix}.{key}")
    else:
        yield prefix, value


def changed_inputs(scenario, nominal):
    """Input fields that differ from the nominal example: each one is a number someone chose."""
    base = dict(leaves({k: v for k, v in nominal.items() if k != "decision"}, "input"))
    current = dict(leaves({k: v for k, v in scenario["input"].items() if k != "decision"}, "input"))
    return [path for path, value in current.items() if base.get(path) != value]


def problems():
    known = sources()
    nominal = load(SHARED / "examples" / "nominal.json")
    schema = load(SHARED / "telemetry.schema.json")
    hrp = load(SHARED / "hrp.json")
    found = []

    for kind, key in (("hazards", "hazard"), ("risks", "hrpRisk")):
        if list(hrp[kind]) != schema["$defs"][key]["enum"]:
            found.append(f"shared/hrp.json {kind} and the schema's {key} enum differ")
        found += [f"shared/hrp.json {kind}.{rid}: unknown source {e['source']}" for rid, e in hrp[kind].items()
                  if e["source"] not in known]

    for path in sorted((SHARED / "examples").glob("*.json")):
        for factor in load(path)["decision"]["factors"]:
            if factor["source"] is not None and factor["source"] not in known:
                found.append(f"{path.relative_to(ROOT)}: factor {factor['signal']} cites unknown source {factor['source']}")

    for scenario in scenarios():
        name = scenario["name"]
        entries = scenario.get("provenance", [])
        covered = set()
        for entry in entries:
            covered.update(entry["claims"])
            if entry["kind"] not in ("source", "assumption"):
                found.append(f"{name}: kind must be source or assumption, not {entry['kind']}")
            if entry["kind"] == "source" and entry.get("ref") not in known:
                found.append(f"{name}: {entry['claims']} cites unknown source {entry.get('ref')}")
            if entry["kind"] == "assumption" and not entry.get("note"):
                found.append(f"{name}: assumption {entry['claims']} needs a note saying why")
            if entry["kind"] == "assumption" and "ref" in entry and entry["ref"] not in known:
                found.append(f"{name}: unknown ref {entry['ref']}")
        for claim in [*REQUIRED_CLAIMS, *changed_inputs(scenario, nominal)]:
            if claim not in covered:
                found.append(f"{name}: {claim} has no provenance (cite a source or mark it as an assumption)")
    return found


def render() -> str:
    known = sources()
    hrp = load(SHARED / "hrp.json")
    out = [
        "# Sources",
        "",
        "Generated by `make sources` from `shared/sources.json`, `shared/hrp.json` and `shared/scenarios/`. Do not edit by hand.",
        "",
        "Every number and label SYNAPSE shows traces back to one of these sources, or is listed below as an open assumption.",
        "The official challenge resources are context pages, not datasets: they give the hazard and risk taxonomy and the",
        "rationale; thresholds come from the papers, and training data from the datasets.",
        "",
        "## Registry",
        "",
        "| Id | Type | Source | What we take from it |",
        "|---|---|---|---|",
    ]
    for sid, s in known.items():
        out.append(f"| `{sid}` | {s['type']} | [{s['title']}]({s['url']}) | {'; '.join(s['findings'])} |")

    out += ["", "## HRP hazards", "", "| Id | Official name |", "|---|---|"]
    out += [f"| `{hid}` | {h['name']} |" for hid, h in hrp["hazards"].items()]
    out += ["", "## HRP risks", "", "| Id | Official name | Group | Used by SYNAPSE |", "|---|---|---|---|"]
    out += [f"| `{rid}` | {r['name']} | {r['group']} | {r['usedBySynapse'] or '—'} |" for rid, r in hrp["risks"].items()]

    out += ["", "## Scenarios", ""]
    assumptions = []
    for scenario in scenarios():
        out += [f"### {scenario['name']}", "", scenario["description"], "", "| Claim | Kind | Source | Note |", "|---|---|---|---|"]
        for entry in scenario["provenance"]:
            ref = f"`{entry['ref']}`" if entry.get("ref") else "—"
            claims = ", ".join(f"`{c}`" for c in entry["claims"])
            out.append(f"| {claims} | {entry['kind']} | {ref} | {entry['note']} |")
            if entry["kind"] == "assumption":
                assumptions.append((scenario["name"], claims, entry["note"]))
        out.append("")

    out += ["## Open assumptions", "", f"{len(assumptions)} claims are not backed by a source yet. Say so if the judges ask.", "",
            "| Scenario | Claim | Why |", "|---|---|---|"]
    out += [f"| {name} | {claims} | {note} |" for name, claims, note in assumptions]
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    DOC.write_text(render(), encoding="utf-8")
    print(f"wrote {DOC.relative_to(ROOT)}")
