"""Plain-English report of the YawDD calibration, rendered from the metrics JSON.

Every number in the report is read from ``yawn_metrics.json`` / ``yawn_params.json``;
nothing is typed by hand. No image is produced (YawDD licence).
"""

from __future__ import annotations

CONDITION_LABEL = {
    "normal": "Normal",
    "talking": "Talking",
    "yawning": "Yawning",
    "talking_yawning": "Talking&Yawning",
    "mixed": "mixed (Dash)",
}


def _pct(value: float | None, digits: int = 1) -> str:
    return "n/a" if value is None else f"{100 * value:.{digits}f} %"


def _prop(p: dict) -> str:
    if not p["of"]:
        return "no videos"
    low, high = p["ci95_wilson"]
    return f"{p['count']}/{p['of']} ({_pct(p['rate'])}; 95 % CI {100 * low:.1f}-{100 * high:.1f})"


def _short(p: dict) -> str:
    return "-" if not p["of"] else f"{p['count']}/{p['of']} ({_pct(p['rate'])})"


def _num(value: float | None, digits: int = 2) -> str:
    return "n/a" if value is None else f"{value:.{digits}f}"


def _params(p: dict) -> str:
    text = f"threshold {p['threshold']:g}, minimum duration {p['min_duration_s']:g} s, release factor {p['release_factor']:g}"
    if p.get("baseline_window_s") is not None:
        text += f", baseline window {p['baseline_window_s']:g} s"
    return text


def _table(header: list[str], rows: list[list[str]]) -> list[str]:
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    lines += ["| " + " | ".join(row) + " |" for row in rows]
    return lines + [""]


def _metric_row(label: str, m: dict) -> list[str]:
    per_minute = m["yawns_per_minute"]
    return [
        label,
        _prop(m["yawning_recall"]),
        _prop(m["talking_false_alarm"]),
        _prop(m["normal_false_alarm"]),
        _num(per_minute.get("talking")),
        _num(per_minute.get("normal")),
    ]


def _breakdown_rows(groups: dict) -> list[list[str]]:
    return [
        [
            name,
            _short(m["yawning_recall"]),
            _short(m["talking_false_alarm"]),
            _short(m["normal_false_alarm"]),
            _num(m["yawns_per_minute"].get("talking")),
            _num(m["yawns_per_minute"].get("normal")),
        ]
        for name, m in groups.items()
    ]


def render(metrics: dict, params: dict) -> str:
    dataset = metrics["dataset"]
    extraction = metrics["extraction"]
    results = metrics["results"]
    chosen = results["chosen_variant"]
    other = "relative" if chosen == "absolute" else "absolute"
    final = metrics["final_params"]
    mirror = dataset["videos_per_condition"].get("mirror", {})
    dash_count = dataset["videos_per_condition"].get("dash", {}).get("mixed", 0)
    timing = metrics["timing"]
    lines: list[str] = []
    add = lines.append

    add("# Yawn detection measured on YawDD")
    add("")
    if metrics["limit"]:
        add(f"> **Smoke run** (`--limit {metrics['limit']}`): a subset of the dataset. These numbers are not the result.")
        add("")
    add(f"Generated by `{metrics['command']}` on {metrics['generated_at']}. Every number below comes from")
    add("`yawn_metrics.json`, produced by that run. It is not a medical device and this is not a clinical validation.")
    add("")

    add("## What was measured")
    add("")
    add(
        f"- **Data**: YawDD, {dataset['videos_used']} videos of drivers in cars "
        f"({extraction['frame_size'][0]}, {', '.join(str(f) for f in extraction['source_fps'])} fps, no audio). "
        f"The *Mirror* set has one label per video, taken from the file name: "
        f"{mirror.get('normal', 0)} Normal, {mirror.get('talking', 0)} Talking, {mirror.get('yawning', 0)} Yawning "
        f"and {mirror.get('talking_yawning', 0)} Talking&Yawning videos of {dataset['subjects'].get('mirror', 0)} people. "
        f"The *Dash* set has {dash_count} longer videos with no labels in time."
    )
    add(
        f"- **Landmarks**: MediaPipe `FaceLandmarker` ({extraction['running_mode']} mode, Python "
        f"{', '.join(extraction['mediapipe_version'])}) with the model file the browser loads "
        f"(`{extraction['model_file']}`), on one frame in every "
        f"{'/'.join(str(s) for s in extraction['frame_step'])}: "
        f"{', '.join(str(f) for f in extraction['processed_fps'])} fps, G1's minimum frame rate. "
        f"{extraction['processed_frames']} frames in total."
    )
    add(f"- **Feature** (`{metrics['feature']['name']}`): {metrics['feature']['formula']}.")
    names = ", ".join(f"{name} = {index}" for name, index in metrics["feature"]["landmarks"].items())
    add(f"  Landmark indices: {names}.")
    add(
        "- **Detector**: the mouth is open from the first frame with the ratio at or above the threshold and stays "
        "open while it is at or above `release factor x threshold`; an open stretch that lasts at least the minimum "
        "duration is one yawn. Frames with no face are missing, not zero; a stretch survives at most "
        f"{metrics['detector']['grid']['max_gap_s']:g} s without a confirming frame (fixed, not searched)."
    )
    add(
        "- **Two variants**: *absolute* compares the ratio with the threshold; *relative* compares it with a "
        "per-video baseline (median of the first seconds) plus the threshold."
    )
    add(
        f"- **Validation**: {metrics['validation']['scheme']}. Threshold, minimum duration, release factor (and "
        "baseline window) are searched on the train folds only, maximising "
        f"`{metrics['detector']['selection_score']}`; the numbers below are from the test folds, pooled. "
        "No person is in both the train and the test side of a fold."
    )
    add("")

    add("## Result")
    add("")
    add(f"**Chosen: the {chosen} variant, {_params(final[chosen]['params'])}.**")
    add("")
    add(
        f"These final parameters come from the same search run on all {sum(mirror.get(c, 0) for c in ('normal', 'talking', 'yawning'))} "
        f"labelled Mirror videos (grid points tied for the best score: {final[chosen]['candidates_tied']}; on a tie "
        "the one in the middle of the tied region is taken). The measured performance is the out-of-fold table, "
        "not the fit on all videos."
    )
    add("")
    add("Out-of-fold, video level. A video counts as detected when at least one yawn is found in it.")
    add("")
    rows = [
        _metric_row(f"{chosen} (chosen)", results[chosen]["overall"]),
        _metric_row(other, results[other]["overall"]),
        _metric_row("variant chosen on train folds", results["variant_chosen_on_train_folds"]["overall"]),
    ]
    lines += _table(
        [
            "Variant",
            "Yawning videos with a yawn (recall)",
            "Talking videos with a yawn (false alarm)",
            "Normal videos with a yawn (false alarm)",
            "Yawns/min in Talking",
            "Yawns/min in Normal",
        ],
        rows,
    )
    score = results["out_of_fold_score"]
    add(
        f"Selection score out of fold: absolute {_num(score['absolute'], 4)}, relative {_num(score['relative'], 4)}. "
        f"{results['chosen_by']}"
    )
    per_fold_choice = results["variant_chosen_on_train_folds"]["variant_per_fold"]
    intervals = {
        key: [results[v]["overall"][key]["ci95_wilson"] for v in (chosen, other)]
        for key in ("yawning_recall", "talking_false_alarm")
    }
    overlap = {
        key: bool(a and b and a[0] <= b[1] and b[0] <= a[1]) for key, (a, b) in intervals.items()
    }
    add("")
    add(
        "Read the three rows together. On the train folds alone the search preferred the relative variant in "
        f"{per_fold_choice.count('relative')} of {len(per_fold_choice)} folds and the absolute one in "
        f"{per_fold_choice.count('absolute')}; the third row is what that fully automatic choice gives on unseen people. "
        f"The 95 % intervals of the two variants {'overlap' if overlap['yawning_recall'] else 'do not overlap'} on recall "
        f"and {'overlap' if overlap['talking_false_alarm'] else 'do not overlap'} on Talking false alarms."
    )
    per_video = results[chosen]["overall"].get("yawns_per_yawning_video")
    if per_video:
        add("")
        add(
            f"Detected yawns per Yawning video: mean {_num(per_video['mean'])}, median {_num(per_video['median'], 1)}, "
            f"max {per_video['max']}. YawDD does not say how many yawns a video holds, so this count has no ground truth."
        )
    add("")

    add("### Parameters chosen in each fold")
    add("")
    fold_rows = []
    for variant in (chosen, other):
        for report in results[variant]["per_fold"]:
            test = report["test"]
            fold_rows.append(
                [
                    variant,
                    str(report["fold"]),
                    _params(report["params"]),
                    str(report["candidates_tied_on_train"]),
                    _short(test["yawning_recall"]),
                    _short(test["talking_false_alarm"]),
                    _short(test["normal_false_alarm"]),
                ]
            )
    lines += _table(
        ["Variant", "Fold", "Chosen on train", "Tied candidates", "Test recall", "Test Talking FA", "Test Normal FA"],
        fold_rows,
    )

    add(f"### By eyewear and facial hair ({chosen} variant, out of fold)")
    add("")
    add("Groups come from the file names only (`NoGlasses`, `Glasses`, `SunGlasses`, `moustache`, `Beard`).")
    add("")
    header = ["Group", "Yawning recall", "Talking false alarm", "Normal false alarm", "Yawns/min Talking", "Yawns/min Normal"]
    lines += _table(
        header,
        [[f"eyewear: {r[0]}", *r[1:]] for r in _breakdown_rows(results[chosen]["by_eyewear"])]
        + [[f"facial hair: {r[0]}", *r[1:]] for r in _breakdown_rows(results[chosen]["by_facial_hair"])]
        + [[f"sex: {r[0]}", *r[1:]] for r in _breakdown_rows(results[chosen]["by_sex"])],
    )

    add(f"### Videos the {chosen} detector gets wrong (out of fold)")
    add("")
    errors = results[chosen]["errors"]
    missed = errors["missed_yawning_videos"]
    never = errors.get("missed_never_reaching_fold_threshold")
    if missed:
        text = f"Yawning videos with no detected yawn: {len(missed)}."
        if never is not None:
            text += (
                f" In {never} of them the ratio never reaches the threshold of their fold in any frame, so no "
                f"minimum duration could have found them; in the other {len(missed) - never} it does, but not for long enough."
            )
        add(text)
        add("")
        lines += _table(
            ["Video", "Highest ratio in the video", "Frames without a face"],
            [[f"`{v['video']}`", _num(v["max_ratio"], 3), _pct(v["no_face_rate"])] for v in missed],
        )
    else:
        add("No Yawning video was missed.")
        add("")
    false_alarms = errors["false_alarm_videos"]
    if false_alarms:
        add(f"Talking or Normal videos with a detected yawn: {len(false_alarms)}.")
        add("")
        lines += _table(
            ["Video", "Detected yawns", "Highest ratio in the video"],
            [[f"`{v['video']}`", str(v["detected_yawns"]), _num(v["max_ratio"], 3)] for v in false_alarms],
        )
    else:
        add("No Talking or Normal video raised a yawn.")
        add("")

    add("### Talking&Yawning videos (reported apart)")
    add("")
    for variant in (chosen, other):
        mixed = results[variant]["talking_and_yawning_videos"]
        add(
            f"- {variant}: videos with at least one detected yawn: {_prop(mixed['with_detected_yawn'])}; "
            f"{mixed['detected_yawns']} yawns in total, {_num(mixed['yawns_per_minute'])} per minute."
        )
    add("")
    add("They were never used to choose parameters. Each is expected to contain a yawn, between stretches of talking.")
    add("")

    add("### How long the mouth stays open")
    add("")
    add(
        f"Longest stretch above the final {chosen} threshold in each Mirror video, in seconds. "
        "This is the margin the minimum duration works with."
    )
    add("")
    longest = metrics["longest_open_episode_s_at_final_threshold"]
    lines += _table(
        ["Condition", "min", "p10", "p25", "median", "p75", "p90", "max"],
        [
            [CONDITION_LABEL[c], *[_num(longest[c][k]) for k in ("min", "p10", "p25", "p50", "p75", "p90", "max")]]
            for c in ("normal", "talking", "yawning", "talking_yawning")
            if longest.get(c)
        ],
    )

    add("### Frames with no face")
    add("")
    no_face = metrics["no_face"]
    lines += _table(
        ["Set / group", "Videos", "Frames", "No-face frames", "Rate", "Videos with any"],
        [
            [key, str(v["videos"]), str(v["frames"]), str(v["no_face_frames"]), _pct(v["rate"], 2), str(v["videos_with_any_no_face_frame"])]
            for section in ("by_camera_and_condition", "by_camera_and_eyewear")
            for key, v in no_face[section].items()
        ],
    )
    over = no_face["videos_over_5_percent"]
    if over:
        add(f"Videos with more than 5 % of frames without a face ({len(over)}):")
        add("")
        for item in over:
            add(f"- `{item['video']}`: {_pct(item['rate'])} of {item['frames']} frames")
        add("")
    else:
        add("No video has more than 5 % of its frames without a face.")
        add("")

    runs = no_face.get("runs_of_frames_without_a_face")
    if runs:
        add(
            f"Runs of consecutive frames without a face in the Mirror videos, and how many of them sit next to a "
            f"frame with the mouth open (ratio at or above {runs['open_threshold']:g}):"
        )
        add("")
        lines += _table(
            ["Condition", "Runs", "Next to an open mouth", "Longest run (frames)"],
            [
                [CONDITION_LABEL[c], str(v["runs"]), str(v["runs_beside_open_mouth"]), str(v["longest_run_frames"])]
                for c, v in runs["by_condition"].items()
            ],
        )
    sensitivity = metrics["max_gap_sensitivity"]["values"]
    add(
        "The detector bridges at most "
        f"{metrics['detector']['grid']['max_gap_s']:g} s without a confirming frame. That value is fixed, not searched. "
        "Out-of-fold result of the absolute variant with other values:"
    )
    add("")
    lines += _table(
        ["max_gap_s", "Yawning recall", "Talking false alarm", "Normal false alarm", "Score"],
        [[value, *_alt_cells(v)] for value, v in sensitivity.items()],
    )

    add("### Is the start of a video calm? (the relative variant assumes so)")
    add("")
    check = metrics["baseline_check"]
    add(
        "The product will measure a person's resting mouth at session start. In YawDD the baseline can only be the "
        "first seconds of each video, and nothing guarantees they are calm. Measured:"
    )
    add("")
    baseline_rows = []
    for window, by_condition in check["baseline_by_window_and_condition"].items():
        for condition in ("normal", "talking", "yawning"):
            q = by_condition.get(condition)
            if q:
                baseline_rows.append([window, CONDITION_LABEL[condition], _num(q["p50"], 3), _num(q["p90"], 3), _num(q["max"], 3)])
    lines += _table(["Baseline window", "Condition", "median baseline", "p90", "max"], baseline_rows)
    inside = check["yawning_videos_first_yawn_inside_window"]
    add(
        "Yawning videos whose first detected yawn (absolute detector, final parameters) starts inside the window: "
        + "; ".join(f"{window}: {_short(p)}" for window, p in inside.items())
        + "."
    )
    add("")

    add("## Dash set: descriptive only")
    add("")
    dash = metrics["dash_descriptive"]
    add(
        f"The {dash['videos']} Dash videos mix normal driving, talking and yawning with no time marks, so there is "
        "nothing to score. These are counts of what the detector fires on with the final parameters, **not accuracy**."
    )
    add("")
    dash_rows = []
    for variant in (chosen, other):
        d = dash[variant]
        q = d["yawns_per_minute_per_video"] or {}
        dash_rows.append(
            [
                variant,
                str(d["total_yawns"]),
                _num(d["total_minutes"], 1),
                _num(d["yawns_per_minute_pooled"]),
                _num(q.get("p50")),
                f"{_num(q.get('min'))}-{_num(q.get('max'))}",
                f"{d['videos_with_detected_yawn']}/{dash['videos']}",
            ]
        )
    lines += _table(
        ["Variant", "Yawns", "Minutes", "Yawns/min (pooled)", "Yawns/min (median video)", "Range per video", "Videos with a yawn"],
        dash_rows,
    )
    add(f"Per video ({chosen} variant):")
    add("")
    lines += _table(
        ["Video", "Minutes", "Yawns", "Yawns/min"],
        [[f"`{v['video']}`", _num(v["minutes"]), str(v["yawns"]), _num(v["yawns_per_minute"])] for v in dash[chosen]["per_video"]],
    )

    add("## Other ways to measure the mouth (information only)")
    add("")
    alternatives = metrics["alternative_features"]
    add(
        "Same folds and search with absolute thresholds. The detector parameters use the product formula; "
        "these rows only show what the out-of-fold result would be with another measure."
    )
    add("")
    alt_rows = [["product formula (`" + metrics["feature"]["name"] + "`)", *_alt_cells(alternatives["product_formula_absolute"])]]
    for name, value in alternatives.items():
        if isinstance(value, dict) and name != "product_formula_absolute":
            alt_rows.append([f"`{name}`", *_alt_cells(value)])
    lines += _table(["Measure", "Yawning recall", "Talking false alarm", "Normal false alarm", "Score"], alt_rows)

    add("## Run time")
    add("")
    add(
        f"- MediaPipe: {_num(timing['mediapipe_ms_per_frame_mean'])} ms per frame on average "
        f"({timing['processed_frames']} frames, {_num(timing['mediapipe_seconds_sum'], 0)} s summed over videos; "
        f"{_num(timing['decode_plus_mediapipe_seconds_sum'], 0)} s with video decoding). {timing['note']}"
    )
    for entry in timing["extraction_runs"]:
        add(
            f"- Extraction run of {entry['at']}: {entry['videos']} videos ({entry['frames']} frames) in "
            f"{_num(entry['wall_seconds'], 0)} s of wall time with {entry['workers']} worker processes."
        )
    add(
        f"- This run: {timing['videos_extracted_this_run']} videos extracted, "
        f"{timing['videos_from_cache_this_run']} read from the cache; calibration {_num(timing['calibration_seconds'], 1)} s; "
        f"whole run {_num(timing['run_seconds'], 0)} s. {timing['cpu_count']} logical CPUs, {timing['platform']}."
    )
    add("")

    add("## Limits")
    add("")
    add("- **Acted yawns.** The yawns were performed for the recording; acted yawns may be wider, longer or cleaner than spontaneous ones.")
    add("- **Drivers in cars, not a crew at a laptop.** The camera sits under the front mirror or on the dash, so the face is seen from the side and from above or below, in outdoor light (the dataset tables list sunny, cloudy and rainy). A laptop webcam is frontal, at another distance, in indoor light. The ratio is normalised by face size but not by head pose.")
    add("- **Labels are per video, not per frame.** We know a Yawning video contains a yawn, not when or how many. Recall is \"at least one yawn found in the video\"; a false alarm is \"any yawn found in a Talking or Normal video\". Yawn counts and timing are not validated.")
    add("- **Talking in YawDD is \"talking or singing\"** (dataset readme); the file name is the only label, so any other mouth movement inside a video is unknown to us.")
    add("- **The relative variant was tested on video starts, not on a calibration step.** Its baseline is the first seconds of each video, whatever the person was doing; in the product the baseline would come from a calm moment at session start. So this result does not tell how that variant would do with a proper baseline.")
    add("- **Small groups.** Sunglasses, beard and moustache groups have few videos; read their rows with the counts in view. Facial hair is taken from the file name, and the dataset tables list more bearded participants than the names mark.")
    add("- **One dataset, one camera geometry.** The thresholds are a measured starting point for G1, to be checked against the two G1 fixture videos and a real session; they are not validated for spaceflight.")
    add("- **Python, not the browser.** Same model file and the same formula, but the browser runs it in WebAssembly or on the GPU; small numeric differences are possible and no browser frame rate was measured here.")
    add("- **Hand over the mouth.** When a hand covers a yawn the landmarks under it are estimates; this case was not measured separately.")
    if dataset["videos_failed"]:
        add(f"- **Videos that failed** ({len(dataset['videos_failed'])}): " + "; ".join(f"`{v['video']}` ({v['error']})" for v in dataset["videos_failed"]) + ".")
    add("")

    add("## Dataset notes")
    add("")
    add(f"- Videos found: {dataset['videos_found']}; used: {dataset['videos_used']}; failed: {len(dataset['videos_failed'])}. The dataset readme announces 322 Mirror and 29 Dash videos.")
    if dataset["irregular_names"]:
        add("- Irregular file names, handled explicitly by the parser:")
        for name, reasons in dataset["irregular_names"].items():
            add(f"  - `{name}`: {', '.join(reasons)}")
    if dataset["videos_shorter_than_reported"]:
        add("- Videos that decode fewer frames than their header reports:")
        for item in dataset["videos_shorter_than_reported"]:
            add(f"  - `{item['video']}`: {item['frames_read']} of {item['reported_frames']}")
    add("- The same participant number can appear with several eyewear variants; folds group by camera set + sex + number.")
    add("")

    add("## Licence and citation")
    add("")
    add(dataset["license"])
    add("")
    add(f"> {dataset['citation']}")
    add("")
    add(f"Source id in `shared/sources.json`: `{dataset['source']}`.")
    add("")
    return "\n".join(lines)


def _alt_cells(value: dict) -> list[str]:
    return [
        _short(value["yawning_recall"]),
        _short(value["talking_false_alarm"]),
        _short(value["normal_false_alarm"]),
        _num(value["score"], 4),
    ]
